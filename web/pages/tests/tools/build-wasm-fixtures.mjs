// W10d D-W10-10 fixture generator (platform tests).
// What/why: the wasm-ABI acceptance suite needs a tiny module with a readable
// provenance. Hand-assembling WASM bytes in a test would hide the ABI behind an
// encoder nobody reviews, so the fixture is compiled from fixtures/*.c by the
// documented clang line and inlined here as a byte array. Re-run this script
// after editing a fixture source; --check proves the embedded bytes match.
//
// Usage: node web/pages/tests/tools/build-wasm-fixtures.mjs [--check]
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const fixturesDir = path.join(here, '..', 'fixtures');
const outPath = path.join(here, '..', 'wasm_abi_fixtures.mjs');

const CLANG = process.env.CCGSC_CLANG || 'C:/Program Files/LLVM/bin/clang.exe';
const BASE_FLAGS = [
  '--target=wasm32', '-nostdlib', '-O2', '-ffp-contract=off', '-Wl,--no-entry',
  '-Wl,--max-memory=268435456'
];
// A negative fixture deliberately omits parts of the ABI, so the export list is
// per source: --export names a symbol the linker must find, and a fixture that
// declares fewer functions cannot be built with the full list.
const ABI_EXPORTS = [
  '-Wl,--export=ccgsc_alloc', '-Wl,--export=ccgsc_run', '-Wl,--export=ccgsc_out'
];

const SOURCES = [
  { source: 'wasm_abi_reverse.c', exports: ABI_EXPORTS },
  { source: 'wasm_abi_import.c', exports: ABI_EXPORTS },
  { source: 'wasm_abi_big_mem.c', exports: ABI_EXPORTS },
  { source: 'wasm_abi_no_entry.c', exports: ['-Wl,--export=only_this'] }
];

function build(entry) {
  const out = path.join(fixturesDir, entry.source.replace(/\.c$/, '.wasm'));
  execFileSync(CLANG, [...BASE_FLAGS, ...entry.exports, path.join(fixturesDir, entry.source), '-o', out], { stdio: 'pipe' });
  const bytes = fs.readFileSync(out);
  fs.rmSync(out);
  return bytes;
}

function render(name, bytes) {
  const rows = [];
  for (let i = 0; i < bytes.length; i += 16) {
    rows.push('  ' + Array.from(bytes.subarray(i, i + 16)).join(', ') + ',');
  }
  return `// ${name}: ${bytes.length} bytes, built from fixtures/${name.replace(/\.wasm$/, '.c')}\n` +
    `export const ${name.replace(/\.wasm$/, '').toUpperCase()} = new Uint8Array([\n${rows.join('\n')}\n]);\n`;
}

const parts = [];
for (const entry of SOURCES) {
  parts.push(render(entry.source.replace(/\.c$/, '.wasm'), build(entry)));
}
const generated = '// GENERATED by tools/build-wasm-fixtures.mjs - do not edit.\n' +
  '// Provenance: each block names the fixtures/*.c source it was compiled from.\n' +
  parts.join('\n');

if (process.argv.includes('--check')) {
  const current = fs.existsSync(outPath) ? fs.readFileSync(outPath, 'utf8') : '';
  if (current !== generated) {
    process.stderr.write('wasm_abi_fixtures.mjs is out of date: run node web/pages/tests/tools/build-wasm-fixtures.mjs\n');
    process.exit(1);
  }
  process.stdout.write('wasm fixtures are up to date\n');
} else {
  fs.writeFileSync(outPath, generated, 'utf8');
  process.stdout.write('wrote ' + outPath + '\n');
}
